// Compiles ui/desk.slint, with theme.slint generated from design/tokens.json (every
// colour, and the glass's rgba ones as #rrggbbaa), so the tokens stay the one source.
use std::path::PathBuf;

fn kebab(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            out.push('-');
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// "rgba(16,17,22,0.66)" → "#101116a8".
fn rgba(v: &str) -> Option<String> {
    let inner = v.strip_prefix("rgba(")?.strip_suffix(')')?;
    let p: Vec<f32> = inner.split(',').filter_map(|x| x.trim().parse().ok()).collect();
    (p.len() == 4).then(|| format!("#{:02x}{:02x}{:02x}{:02x}", p[0] as u8, p[1] as u8, p[2] as u8, (p[3] * 255.0).round() as u8))
}

fn main() {
    let tokens_path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../design/tokens.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    let tokens = std::fs::read_to_string(&tokens_path).expect("design/tokens.json");
    let mut theme = String::from("// Generated by apps/desk-slint/build.rs from design/tokens.json: do not edit.\nexport global Theme {\n");
    let mut section = String::new();
    for line in tokens.lines() {
        let t = line.trim();
        if t.ends_with('{') {
            section = t.trim_start_matches('"').split('"').next().unwrap_or("").to_owned();
        }
        let Some((k, v)) = t.split_once(':') else { continue };
        let k = k.trim().trim_matches('"');
        let v = v.trim().trim_end_matches(',').trim_matches('"');
        let value = if v.starts_with('#') && v.len() == 7 { Some(v.to_owned()) } else { rgba(v) };
        if let Some(value) = value {
            let name = if section == "glass" { format!("glass-{}", kebab(k)) } else { kebab(k) };
            theme.push_str(&format!("    out property <color> {name}: {value};\n"));
        }
    }
    theme.push_str("}\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out.join("theme.slint"), theme).unwrap();
    let config = slint_build::CompilerConfiguration::new().with_style("fluent-dark".into()).with_include_paths(vec![out]);
    slint_build::compile_with_config("ui/desk.slint", config).expect("ui/desk.slint");
}
