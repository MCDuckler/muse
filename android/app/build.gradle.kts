// Release signing from key.properties (gitignored); without it the release build is
// signed with the debug key, so a fresh checkout still makes an installable APK.
val keyProps = Properties().apply {
    val f = rootProject.file("key.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

